const localKey = 'forge-ai-plan-v1';

/* Stable fingerprint of everything the program depends on. When it changes
   (goal edited, split day renamed, exercises remapped), the block regenerates. */
export const planFingerprint = (input: unknown) => {
  const text = JSON.stringify(input);
  let hash = 0;
  for (let index = 0; index < text.length; index++) { hash = ((hash << 5) - hash + text.charCodeAt(index)) | 0; }
  return String(hash);
};

const readLocal = (): StoredAiPlan | null => { try { return JSON.parse(localStorage.getItem(localKey) || 'null'); } catch { return null; } };
/* Synchronous cache read for surfaces (Today, Coach) that align to the plan. */
export const readLocalAiPlan = readLocal;
const writeLocal = (stored: StoredAiPlan) => { try { localStorage.setItem(localKey, JSON.stringify(stored)); } catch { /* full */ } };

export async function loadStoredAiPlan(hasUser: boolean): Promise<StoredAiPlan | null> {
  const local = readLocal();
  if (isDemoMode || !hasUser) return local;
  try {
    const { data } = await supabase.from('training_plans').select('payload,generated_at').maybeSingle();
    if (data?.payload) {
      const stored = data.payload as StoredAiPlan;
      writeLocal(stored);
      return stored;
    }
  } catch { /* fall back to local */ }
  return local;
}

export async function saveStoredAiPlan(stored: StoredAiPlan, hasUser: boolean): Promise<void> {
  writeLocal(stored);
  window.dispatchEvent(new Event('forge-ai-plan-changed'));
  if (isDemoMode || !hasUser) return;
  try {
    const { data: userData } = await supabase.auth.getUser();
    if (!userData.user) return;
    await supabase.from('training_plans').upsert({ owner_id: userData.user.id, payload: stored, horizon_weeks: stored.blockWeeks, generated_at: stored.generatedAt }, { onConflict: 'owner_id' });
    /* Every block is kept — regeneration never destroys the record of what
       the program used to prescribe. */
    await supabase.from('training_plan_history').insert({ owner_id: userData.user.id, payload: stored, generated_at: stored.generatedAt });
  } catch { /* local copy still stands */ }
}

export async function generateAiPlan(context: Record<string, unknown>): Promise<AiPlan> {
  const { data, error } = await supabase.functions.invoke('forge-plan', { body: { context } });
  if (error || !data?.plan?.weeks?.length) {
    let detail = 'The plan service did not return a program.';
    const response = (error as { context?: Response } | null)?.context;
    if (response) { try { const body = await response.clone().json(); if (typeof body?.error === 'string') detail = body.error; } catch { /* keep default */ } }
    throw new Error(detail);
  }
  return data.plan as AiPlan;
}

/* ── The 8/6/4/2 wave, shared by every surface ────────────────────────────
   Weeks cycle 8 → 6 → 4 → 2(max attempt). Weights always derive from the
   athlete's CURRENT best calculated max, so the plan reacts to what they
   actually log: beat a prescription and everything scales up; miss one and
   the wave holds steady instead of assuming progress. Max week attempts the
   PR + ~5-10 lb (2.5 kg steps for metric athletes). */
/* Preston's system: a 5-WEEK wave — 8, 6, 4, 2, then MAX WEEK (a true 1RM
   attempt). The running deload lands on the 2-rep week so the max attempt
   always follows a lighter week. */
/* THE LONG RUN IS A SHARE OF THE WEEK, and the share is stated once. The
   roadmap used a flat 35%, the event generator 32%, and the resolver this
   band — three long runs for one week, all on screen together. */
export const LONG_RUN_MIN_SHARE = 0.25;
export const LONG_RUN_MAX_SHARE = 0.35;
/* HOW FAST A LONG RUN MAY GROW, IN ONE PLACE.

   The roadmap grew it 0.3 mi a week from the athlete's lifetime longest; the
   week resolver allowed a mile a week from the longest it could see, recent
   runs included. Two rules for one number, so the roadmap and the program
   printed different long runs for the same week. A mile a week off the
   longest run Forge actually knows about, never below six — which is the
   distance at which "long run" starts meaning anything.

   AND AN ATHLETE WHO HAS LOGGED NOTHING IS NOT AN ATHLETE WITH NO LIMIT. This
   returned Infinity for them, on the theory that the share of the week was the
   only thing that should bind — and the share of the week, on a two-day
   runner with a thirty-mile ceiling, let the plan prescribe a fifteen-mile
   long run to somebody with no running on file at all. "We know nothing about
   this person" is the strongest possible argument for caution, not the
   absence of one. With no evidence the cap starts at six miles and grows a
   mile a week, exactly as it would for someone who had logged a six-miler. */
export const UNPROVEN_LONG_RUN_MILES = 6;
/* And an athlete who has logged NOTHING does not climb forever on the strength
   of weeks passing. Growth is earned by covering the distance: without a single
   logged run the cap starts at six miles, grows a mile a week like anyone
   else's, and stops at ten. Past that, log a run — which is the whole premise
   of the app, and the one place it was quietly making an exception. */
export const UNPROVEN_LONG_RUN_CEILING = 10;
export const longRunCap = (longestKnown: number, weekIndex: number) =>
  longestKnown > 0
    ? Math.max(6, longestKnown + 1 + Math.max(0, weekIndex))
    : Math.min(UNPROVEN_LONG_RUN_CEILING, UNPROVEN_LONG_RUN_MILES + Math.max(0, weekIndex));
export const WAVE_REPS = [8, 6, 4, 2, 1] as const;
export const WAVE_LENGTH = WAVE_REPS.length;
export const waveSlot = (weekIndex: number) => ({ reps: WAVE_REPS[weekIndex % WAVE_LENGTH], isMax: weekIndex % WAVE_LENGTH === WAVE_LENGTH - 1 });

/* THE BLOCK OWNS THE MAX WEEK. THE LIFT OWNS ITS RUNG.

   A lift's rung is counted in the sessions it has actually answered, which is
   right — lifts are trained at different rates and a fortnightly movement
   should not be dragged along by the calendar. But the 1 at the top of
   8/6/4/2/1 is not a rung like the others: it is a TEST, and a test is an
   event the block schedules, not something a lift wanders into because its own
   session count happened to land on five.

   Preston opened week 1 of a ten-week block to "Squat 520 x 1" under a banner
   reading "4-REP WEEK" — 45 lb over his tested single, on a lift that had not
   ramped at all, in a week the block had called a build week. Two clocks, and
   the dangerous one won.

   So an ordinary week walks each lift up its own ramp — 8, 6, 4, 2, and back
   to 8 — and no week but the block's max week ever asks for a single. */
export const RAMP_REPS = [8, 6, 4, 2] as const;
export const RAMP_LENGTH = RAMP_REPS.length;
export const rampReps = (rung: number) => RAMP_REPS[((Math.round(rung) % RAMP_LENGTH) + RAMP_LENGTH) % RAMP_LENGTH];
/* How many times a lift has to have been trained inside the block before it is
   allowed to test. A cold max is not a max, it is an injury with a number. */
export const EXPOSURES_BEFORE_MAX = 3;
/* HOW FAR A BLOCK MAY OUTRUN A TESTED SINGLE.

   A calculated max is an inference from rep work; a tested single is a fact.
   When they disagree the fact wins, and Preston's disagreed by a lot — an
   all-out 415 x 8 estimates 526 while the bar he had actually taken for one
   was 475. Every rung written off 526 was about a tenth too heavy, which is
   how a ten-week block opened by asking for 45 lb over his best ever single.

   So a lift with a tested single is written from a max no more than five
   percent past it. Rep work still moves the number — the single is re-tested
   every max week and the ceiling moves with it — but it moves a block at a
   time, not in one jump off an estimate. */
export const MAX_OVER_TESTED = 1.05;

/* THE MAX FORGE IS WILLING TO ACT ON, which is not always the one arithmetic
   produces. A calculated max is an inference from rep work and a generous one;
   a tested single is a fact. Where both exist the inference is held to five
   percent over the fact — the same bound the wave is written under, so
   anything asking "has this athlete passed what the block prescribes" compares
   like with like.

   Without a tested single there is nothing to hold it to and the calculation
   stands: an athlete who has put up 500 for a double has genuinely outrun a
   block topping out at 495, and saying otherwise would pin them to a program
   they have already beaten. */
export const provenMax = (calculated: number, tested: number) =>
  tested > 0 ? Math.min(calculated, tested * MAX_OVER_TESTED) : calculated;

/* A LIFT WITH NO GOAL ON IT IS NOT TRAINED LIKE ONE THAT HAS.

   The 8/6/4/2/1 wave exists to walk a lift up to a tested single. An accessory
   has no single to walk to — running it up the same wave spends heavy, risky
   sets on a movement nothing is being measured against, and it is why a
   non-goal lift used to end its wave on a heavy double it had no reason to
   take. Accessories run 12/10/8/6 instead: rep work, off the calculated max,
   and they advance PER SESSION on that lift rather than per calendar week,
   because an accessory trained once a fortnight should not be four rungs along
   because the block is four weeks old.

   The load climbs one plate step every fifth completed session, and the raise
   compounds — it stacks on the max it already raised, so 100 becomes 105 and
   then 110, not 105 twice. */
export const ACCESSORY_REPS = [12, 10, 8, 6] as const;
export const ACCESSORY_LENGTH = ACCESSORY_REPS.length;
export const ACCESSORY_SESSIONS_PER_RAISE = 5;
export const accessorySlot = (sessionIndex: number) => ({ reps: ACCESSORY_REPS[Math.max(0, sessionIndex) % ACCESSORY_LENGTH] });

/* AFTER THE THIRD MISS, THE PLAN STOPS ASKING. Forge writes one plate step
   over the athlete's own best set at a rep count and waits to be beaten. Wait
   forever and the same bar sits there every session with nothing behind it but
   optimism. Three failed attempts at a rep count and the prescription returns
   to the last load actually completed there — no step on top — until the
   athlete succeeds again, which clears the count. */
export const FAILURES_BEFORE_BACKOFF = 3;

/* WHEN A SET ANSWERS WHAT THE PLAN ASKED.

   The tolerance runs one way. Asked for two and got three is the set — an extra
   rep is not a different session, and there is no credit for it. Asked for two
   and got ONE is not the set: that is coming up short, which is what the
   three-miss back-off exists to answer. Asked for two and got eight is neither
   — that is a different session, and it is off script.

   This lives here, beside the wave, because it is a training rule and not a
   detail of how progression is counted. Everything that asks "did they do it"
   asks here. */
export const REP_TOLERANCE = 1;
export const answeredThePlan = (asked: number, did: number) => did >= asked && did <= asked + REP_TOLERANCE;

