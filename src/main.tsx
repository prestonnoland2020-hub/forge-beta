/* THE LAUNCH STEPS ASIDE once React has painted its first screen AND the
   strike has finished — the last facet landing, plus a beat to hold the
   finished F, which brings it to the 1.2s signature. It waits on the animation itself rather than a clock, because the
   browser can start it late on a slow first load and a timer would cut it off
   halfway. A fast device never cuts it short; the 4s backstop means a stalled
   animation can never hold the app hostage. Under reduced motion nothing
   animates, so there is nothing to wait for. */
function clearLaunch() {
  const boot = document.getElementById('forge-boot');
  if (!boot) return;
  let done = false;
  const leave = () => {
    if (done) return;
    done = true;
    boot.classList.add('is-leaving');
    window.setTimeout(() => boot.remove(), 300);
  };
  if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) { boot.remove(); return; }
  const last = boot.querySelector('.fb-base');
  const running = last?.getAnimations().some(animation => animation.playState !== 'finished');
  if (!last || !running) { window.setTimeout(leave, 300); return; }
  last.addEventListener('animationend', () => window.setTimeout(leave, 300), { once: true });
  window.setTimeout(leave, 4000);
}

